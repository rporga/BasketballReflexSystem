import assert from 'node:assert/strict';
import {liveWinEstimate,minutesRemaining} from '../lib/live-win-model.js';
const game=(status,period,clock,home,away)=>({status,period,clock,home:{score:home},away:{score:away}});
assert.equal(minutesRemaining(1,'12:00'),48);
assert.equal(minutesRemaining(3,'05:30'),18.5);
assert.equal(minutesRemaining(4,'00:00'),0);
assert.equal(minutesRemaining(5,'03:40'),3+40/60);
assert.equal(minutesRemaining(3,'bad clock'),null);
const pre=liveWinEstimate(game('pre',0,'0:00',0,0),57);
assert.equal(pre.kind,'pregame');assert.equal(pre.homePct,57);
const tie=liveWinEstimate(game('in',1,'12:00',0,0),55);
assert.equal(tie.kind,'live');assert.equal(tie.homePct,55);
const first=liveWinEstimate(game('in',2,'06:00',51,49),55);
const next=liveWinEstimate(game('in',2,'05:45',55,49),55);
assert.ok(next.homePct>first.homePct,'Scoring lead improves estimated probability when time decreases');
const late=liveWinEstimate(game('in',4,'00:35',103,98),55);
assert.ok(late.homePct>next.homePct,'Big lead in final seconds strongly impacts heuristic');
const reversed=liveWinEstimate(game('in',4,'00:35',98,103),55);
assert.ok(reversed.homePct<50,'Trailing late lowers the forecast');
const noPrior=liveWinEstimate(game('in',3,'08:30',70,70));
assert.equal(noPrior.homePct,50);assert.equal(noPrior.hasPrior,false);
const bad=liveWinEstimate(game('in',4,'',110,107),55);
assert.equal(bad.kind,'unavailable');
const final=liveWinEstimate(game('post',4,'00:00',110,100),55);
assert.equal(final.kind,'final');assert.equal(final.winner,1);
assert.equal(liveWinEstimate(game('pre',0,'',0,0)).homePct,null);
console.log('PASS live score/clock estimates, changes, pregame, final and missing feeds');
