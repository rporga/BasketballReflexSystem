import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8');
const layout=read('app/layout.jsx');
const page=read('app/page.jsx');
const scouting=read('app/IntelligencePanel.jsx');
const backend=read('app/api/intelligence/route.js');
const robots=read('app/robots.js');
const sitemap=read('app/sitemap.js');
const about=read('app/about/page.jsx');
const dime=read('app/api/dime/route.js');
assert.ok(layout.includes("default: 'Pick & Roll'"),'Canonical product title');
assert.ok(layout.includes('Understand the game. Anticipate what happens next.'),'Tagline in meta');
assert.ok(layout.includes('Live NBA intelligence that connects player performance, matchups, rotations and statistical projections in one place.'),'Complete meta description');
assert.ok(layout.includes('alternates: { canonical:'),'Canonical URL');
assert.ok(layout.includes("'WebSite'"),'Schema.org WebSite source');
assert.ok(page.includes('<h1>Pick &amp; Roll</h1>'),'Indexable homepage heading');
assert.ok(page.includes('brand-intro-description'),'Indexable homepage description');
assert.ok(page.includes('href="/about"'),'Discoverable About page');
assert.ok(!scouting.includes('Key Takeaways')&&!scouting.includes(' SIGNALS')&&!scouting.includes('matchup edge'),'No speculative labels in scouting');
assert.ok(scouting.includes('Too close to call'),'Close game state');
assert.ok(scouting.includes('SMALL SAMPLE'),'Historical sample caution');
assert.ok(backend.includes('sampleLabel:counts'),'Backend includes observation sample counts');
assert.ok(backend.includes("get(ESPN+'/teams?limit=50'"),'Canonical team registry');
assert.ok(dime.includes('const r=await playerProps(playerId)'),'Dime canonical game logs');
assert.ok(robots.includes("disallow: ['/api/']"),'API excluded from crawling');
assert.ok(sitemap.includes("'/about'"),'Sitemap includes About');
assert.ok(about.includes('0.184')&&about.includes('346'),'Validated baseline disclosed');
console.log('PASS Pick & Roll SEO, canonical team/player data, observation samples and About page');
